// Generates Android vector drawables for the home screen widget from the same
// lucide icons the app uses (src/lib/icons.tsx). Run after changing ICONS:
//   node scripts/gen-widget-icons.mjs
import { readFileSync, writeFileSync, readdirSync, unlinkSync } from 'node:fs'
import { pathToFileURL } from 'node:url'

const root = new URL('..', import.meta.url).pathname
const out = `${root}android/app/src/main/res/drawable`
const iconsSrc = readFileSync(`${root}src/lib/icons.tsx`, 'utf8')
const entries = [...iconsSrc.matchAll(/\{ key: '([\w-]+)', Icon: (\w+) \}/g)].map(([, key, name]) => ({ key, name }))
if (entries.length === 0) throw new Error('No icons found in src/lib/icons.tsx')

// Flower2 -> flower-2, BookOpen -> book-open
const kebab = (name) => name.replace(/([a-z])([A-Z0-9])/g, '$1-$2').replace(/([0-9])([A-Z])/g, '$1-$2').toLowerCase()

/**
 * Rewrites SVG path data so every number is separated. Minified arcs like
 * "a5 5 0 0012 5" pack the two flags against the next number; browsers accept
 * that, Android's path parser doesn't.
 */
function normalizePath(d) {
  const out = []
  let i = 0
  let cmd = ''
  let arg = 0
  const num = /^[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?/
  while (i < d.length) {
    const ch = d[i]
    if (/[\s,]/.test(ch)) {
      i++
    } else if (/[a-zA-Z]/.test(ch)) {
      cmd = ch
      arg = 0
      out.push(ch)
      i++
    } else if (/[aA]/.test(cmd) && (arg % 7 === 3 || arg % 7 === 4)) {
      // Arc flags are a single 0 or 1.
      out.push(ch)
      arg++
      i++
    } else {
      const m = d.slice(i).match(num)
      if (!m) throw new Error(`Bad path data at ${i}: ${d}`)
      out.push(m[0])
      arg++
      i += m[0].length
    }
  }
  return out.join(' ').replace(/ ([a-zA-Z]) /g, '$1').replace(/^([a-zA-Z]) /, '$1')
}

/** Fails like Android's PathParser would: each command needs a multiple of its argument count. */
const ARGS = { m: 2, l: 2, h: 1, v: 1, c: 6, s: 4, q: 4, t: 2, a: 7, z: 0 }
function checkPath(d, icon) {
  for (const [, cmd, rest] of d.matchAll(/([a-zA-Z])([^a-zA-Z]*)/g)) {
    const count = rest.trim() ? rest.trim().split(/\s+/).length : 0
    const need = ARGS[cmd.toLowerCase()]
    if (need === undefined || (need === 0 ? count !== 0 : count === 0 || count % need !== 0)) {
      throw new Error(`${icon}: "${cmd}" has ${count} numbers in ${d}`)
    }
  }
  return d
}

const n = (v) => Number(v ?? 0)
function toPath([tag, a]) {
  switch (tag) {
    case 'path':
      return a.d
    case 'circle':
      return ellipse(n(a.cx), n(a.cy), n(a.r), n(a.r))
    case 'ellipse':
      return ellipse(n(a.cx), n(a.cy), n(a.rx), n(a.ry))
    case 'line':
      return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`
    case 'polyline':
    case 'polygon': {
      const pts = a.points.trim().split(/[\s,]+/).map(Number)
      let d = `M${pts[0]} ${pts[1]}`
      for (let i = 2; i < pts.length; i += 2) d += `L${pts[i]} ${pts[i + 1]}`
      return tag === 'polygon' ? d + 'Z' : d
    }
    case 'rect': {
      const x = n(a.x), y = n(a.y), w = n(a.width), h = n(a.height)
      const rx = Math.min(n(a.rx ?? a.ry), w / 2), ry = Math.min(n(a.ry ?? a.rx), h / 2)
      if (!rx) return `M${x} ${y}h${w}v${h}h${-w}Z`
      return `M${x + rx} ${y}h${w - 2 * rx}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${h - 2 * ry}a${rx} ${ry} 0 0 1 ${-rx} ${ry}h${-(w - 2 * rx)}a${rx} ${ry} 0 0 1 ${-rx} ${-ry}v${-(h - 2 * ry)}a${rx} ${ry} 0 0 1 ${rx} ${-ry}Z`
    }
    default:
      throw new Error(`Unsupported SVG element: ${tag}`)
  }
}
const ellipse = (cx, cy, rx, ry) => `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`

/** Loads an icon's data, following alias modules (e.g. smile -> face-slightly-smiling). */
async function loadIcon(file) {
  const path = `${root}node_modules/lucide-react/dist/esm/icons/${file}.mjs`
  const alias = readFileSync(path, 'utf8').match(/export \{ default \} from '\.\/([\w-]+)\.mjs'/)
  if (alias) return loadIcon(alias[1])
  return (await import(pathToFileURL(path).href)).__iconData
}

for (const f of readdirSync(out)) if (f.startsWith('widget_icon_')) unlinkSync(`${out}/${f}`)

for (const { key, name } of entries) {
  const __iconData = await loadIcon(kebab(name))
  const paths = __iconData.node
    .map(
      (el) => `    <path
        android:pathData="${checkPath(normalizePath(toPath(el)), key)}"
        android:strokeColor="#FFFFFFFF"
        android:strokeWidth="2"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:fillColor="#00000000" />`,
    )
    .join('\n')
  writeFileSync(
    `${out}/widget_icon_${key.replace(/-/g, '_')}.xml`,
    `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/gen-widget-icons.mjs from lucide "${kebab(name)}" (ISC license). Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
${paths}
</vector>
`,
  )
}
console.log(`Wrote ${entries.length} widget icons to ${out}`)
